"""Routing table from benchmark results (DESIGN.md §8, Q15/Q25).

For every (task_class, size) the suite covers: the cheapest target whose pass rate clears
AUTO (hand off) or REVIEW (draft + stronger-model review). Cost tier comes from the target's
provider kind: local < free api/client < subscription. Ties: higher pass rate, then faster.
Written to config/routing.toml, which `hx delegate` (sw-lbm.15) reads.
"""

from __future__ import annotations

from collections import defaultdict
from datetime import datetime, timezone

from hx import providers
from hx.bench import SUITE_VERSION
from hx.paths import HARNESS_ROOT

AUTO, REVIEW = 0.9, 0.7
MIN_SAMPLES = 1
TIER = {"local": 0, "api": 1, "client": 1, "subscription": 2}
ROUTING_FILE = HARNESS_ROOT / "config" / "routing.toml"


def infra_error(row: dict) -> bool:
    """Rows that say nothing about the model: refused by a quota/budget gate or never reached it."""
    e = row.get("error") or ""
    return any(s in e for s in ("HTTP Error 429", "URLError", "ConnectionRefused", "ConnectionReset"))


def _verdict(rate: float) -> str:
    return "auto" if rate >= AUTO else "review" if rate >= REVIEW else "no"


def build(rows: list[dict], targets: dict[str, dict], roster: dict[str, providers.Provider]) -> list[dict]:
    """rows: raw bench results (current suite). Returns one route per (task_class, size)."""
    base: dict = defaultdict(lambda: defaultdict(list))  # (cls, size) -> target -> [passed...] at ctx 0
    lat: dict = defaultdict(list)
    ctx_pass: dict = defaultdict(lambda: defaultdict(list))  # (cls, size, target) -> ctx -> [passed]
    level: dict = {}
    for r in rows:
        if r.get("suite_version") != SUITE_VERSION or r.get("target") not in targets or infra_error(r):
            continue
        key = (r["task_class"], r["size"])
        level[key] = r["level"]
        ctx_pass[key + (r["target"],)][r.get("context_tokens") or 0].append(bool(r["passed"]))
        if not (r.get("context_tokens") or 0):
            base[key][r["target"]].append(bool(r["passed"]))
            if r.get("latency_s") is not None:
                lat[key + (r["target"],)].append(r["latency_s"])

    routes = []
    for key in sorted(base, key=lambda k: (level[k], k)):
        cands = []
        for tname, passes in base[key].items():
            if len(passes) < MIN_SAMPLES:
                continue
            t = targets[tname]
            p = roster.get(t.get("provider", ""))
            tier = TIER.get(p.kind, 9) if p else 9
            rate = sum(passes) / len(passes)
            lats = sorted(lat[key + (tname,)])
            ctxs = ctx_pass[key + (tname,)]
            max_ctx = max((c for c, ps in ctxs.items() if sum(ps) / len(ps) >= AUTO), default=None)
            cands.append({"target": tname, "model": t.get("route_model") or t.get("model"),
                          "provider": t.get("provider"), "tier": tier, "pass_rate": round(rate, 3),
                          "n": len(passes), "verdict": _verdict(rate),
                          "p50_s": lats[len(lats) // 2] if lats else None,
                          "max_ctx_passed": max_ctx if max_ctx else None})
        order = {"auto": 0, "review": 1, "no": 2}
        cands.sort(key=lambda c: (order[c["verdict"]], c["tier"], -c["pass_rate"], c["p50_s"] or 1e9))
        best = cands[0] if cands else None
        routes.append({
            "level": level[key], "task_class": key[0], "size": key[1],
            "verdict": best["verdict"] if best else "no",
            "target": best["target"] if best and best["verdict"] != "no" else None,
            "model": best["model"] if best and best["verdict"] != "no" else None,
            "candidates": cands,
        })
    return routes


def to_toml(routes: list[dict], note: str) -> str:
    """Hand-rolled TOML writer (the stdlib only reads TOML)."""
    def val(v):
        if v is None:
            return '""'
        if isinstance(v, bool):
            return "true" if v else "false"
        if isinstance(v, (int, float)):
            return repr(v)
        return '"' + str(v).replace("\\", "\\\\").replace('"', '\\"') + '"'

    out = [
        "# Generated by `hx bench route --write` from benchmark results. Do not edit by hand:",
        "# re-run the ladder and regenerate. Read by hx delegate (sw-lbm.15).",
        f"# {note}",
        f'suite_version = "{SUITE_VERSION}"',
        f'generated_at = "{datetime.now(timezone.utc).isoformat(timespec="seconds")}"',
        f"auto_threshold = {AUTO}",
        f"review_threshold = {REVIEW}",
        "",
    ]
    for r in routes:
        out.append(f'[route."{r["level"]}/{r["task_class"]}/{r["size"]}"]')
        for k in ("level", "task_class", "size", "verdict", "target", "model"):
            out.append(f"{k} = {val(r[k])}")
        out.append("candidates = [")
        for c in r["candidates"]:
            out.append("  { " + ", ".join(f"{k} = {val(v)}" for k, v in c.items() if v is not None) + " },")
        out.append("]")
        out.append("")
    return "\n".join(out)
