"""Generate the LiteLLM config from config/providers.toml (no LiteLLM import needed).

Only providers whose keys are present get deployments; subscriptions never do.
Output: data/gateway/litellm.yaml plus hx_callbacks.py (the shim LiteLLM loads by file name).
"""

from __future__ import annotations

import json
from pathlib import Path

from hx import keystore, providers
from hx.paths import data_dir

PORT = 4000
LITELLM = "litellm[proxy]==1.106.6"  # pinned; bump deliberately
PYTHON = "3.14"
KEY_NAME = "HX_GATEWAY_KEY"  # local master key, generated on first start


def gateway_dir() -> Path:
    return data_dir() / "gateway"


def alias_map(roster: dict[str, providers.Provider]) -> dict[str, str]:
    return {f"{p.id}/{m['alias']}": p.id for p in roster.values() for m in p.models}


def deployments(roster: dict[str, providers.Provider]) -> tuple[list[dict], list[str]]:
    """(model_list entries, skipped-provider notes)."""
    out, skipped = [], []
    for p in roster.values():
        if p.kind in ("subscription", "client") or not p.models:
            continue
        missing = [k for k in p.keys if not keystore.where(k)]
        if missing:
            skipped.append(f"{p.id}: missing {', '.join(missing)}")
            continue
        for m in p.models:
            params: dict = {"model": (p.litellm_prefix or "openai/") + m["model"]}
            # A templated URL (Cloudflare's {CLOUDFLARE_ACCOUNT_ID}) is left to LiteLLM's provider
            # module, which reads the ids from the environment the gateway is started with.
            if p.base_url and "{" not in p.base_url:
                params["api_base"] = p.base_url
            secret = next((k for k in p.keys if k.endswith(("_API_KEY", "_TOKEN"))), None)
            params["api_key"] = f"os.environ/{secret}" if secret else "none"
            params.update(m.get("params", {}))
            out.append({"model_name": f"{p.id}/{m['alias']}", "litellm_params": params,
                        "model_info": {"hx_provider": p.id}})
    return out, skipped


def render(roster: dict[str, providers.Provider]) -> tuple[dict, list[str]]:
    models, skipped = deployments(roster)
    cfg = {
        "model_list": models,
        "litellm_settings": {
            "callbacks": "hx_callbacks.proxy_handler_instance",
            "drop_params": True,
            "num_retries": 0,  # retries/fallback belong to the caller, after the budget gate
            "telemetry": False,
        },
        "general_settings": {"master_key": f"os.environ/{KEY_NAME}"},
    }
    return cfg, skipped


def write(roster: dict[str, providers.Provider] | None = None) -> tuple[Path, list[str], int]:
    roster = roster or providers.load()
    cfg, skipped = render(roster)
    d = gateway_dir()
    d.mkdir(parents=True, exist_ok=True)
    path = d / "litellm.yaml"
    # JSON is valid YAML; avoids a PyYAML dependency in the harness.
    path.write_text(json.dumps(cfg, indent=2), encoding="utf-8")
    (d / "hx_callbacks.py").write_text(
        "# Generated by hx gateway. LiteLLM loads callbacks by file name next to the config.\n"
        "from hx.gateway.litellm_hooks import proxy_handler_instance  # noqa: F401\n", encoding="utf-8")
    return path, skipped, len(cfg["model_list"])
